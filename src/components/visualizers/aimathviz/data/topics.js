export function getTopicById(id) {
  for (const category of Object.values(topicsData)) {
    const topic = category.topics.find(t => t.id === id);
    if (topic) return topic;
  }
  return null;
}

export function getAllTopics() {
  return Object.values(topicsData).flatMap(category => category.topics);
}

export function getTopicsByCategory(category) {
  return topicsData[category]?.topics || [];
}
